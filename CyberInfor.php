  <h2 class="w3-text-teal">Cybersecurity Topic: Ransomware and Zero Trust Architecture</h2>

  <h4><u>Introduction</u></h4>
  <p>
    Industrial and organizational digitization has led to convenience and innovation while developing substantial cybersecurity threats. The encryption and ransom demand of organization files by malicious software represents one of the most disruptive damaging forms of cyberattacks known as ransomware. These cyberattacks lack sector restrictions because healthcare services and educational institutions together with government agencies and private companies all come under attack. The Federal Bureau of Investigation (2022) confirms that ransomware incidents maintain a global upward trend while causing institutions-level operational and financial breakdowns. Security needs extensive development because perimeter defenses demonstrate their weaknesses during rising cyberattacks. New security models must focus on identity-based protection methods.
  </p>

  <h4><u>Zero Trust Architecture (ZTA) Explanation</u></h4>
  <p>
    Organizations under Zero Trust Architecture (ZTA) adopt a complete system transformation regarding their internal and external access and identity management framework. John Kindervag introduced the concept in 2010 under the “never trust always verify” premise as Zero Trust Architecture (Kindervag, 2010). Every request originating from inside or outside the system receives hostile presumption under ZTA until it obtains both authentication and authorization. Users in ZTA only receive the basic access permissions which match their job role requirements through least-privilege access controls. Obtaining network segmentation together with multi-factor authentication and continuous activity monitoring complements ZTA security. By working together these security methods protect against unapproved system entry and lower the consequences of a security breach.
  </p>

  <h4><u>Advantages</u></h4>
  <p>
    Zero Trust Architecture provides substantial advantages in modern security infrastructures. It minimizes internal and external attack surfaces by granting only role-specific access, limiting unauthorized privilege escalation. Through Replit-based PHP assignments, I applied ZTA-aligned security techniques by implementing SHA-256 hashing for passwords and AES-256-CBC for encryption/decryption in web forms. These coding activities mirrored how real-life organizations secure credentials and sensitive user data. ZTA’s emphasis on identity verification, continuous monitoring, and system segmentation allows early detection and isolation of threats. Additionally, in-class risk management tasks exposed me to real-world security assessments like policy evaluations and vulnerability scans. These approaches further validate how ZTA contributes to a multi-layered defense strategy across cloud, on-premise, and hybrid infrastructures (CISA, 2021).
  </p>

  <h4><u>Conclusion</u></h4>
  <p>
    The increasing dominance of ransomware requires a dramatic rethink of traditional trust-based systems. Zero Trust Architecture redefines cybersecurity strategies by implementing strict access policies, real-time monitoring, and least-privilege authorization. My academic exposure to ZTA through secure coding, risk evaluations, and scholarly research developed both technical and analytical skills to approach cybersecurity practically and responsibly. ZTA not only helps reduce risks but builds a more resilient organizational defense against evolving cyberattacks. As I progress in this field, I plan to further my learning through certifications and hands-on testing, continuing to follow the Zero Trust mindset for securing digital systems.
  </p>


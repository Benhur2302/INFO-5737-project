  <p>
    The Information Security course provided a strong foundation in both theoretical and applied aspects of cybersecurity. From understanding core security principles to engaging in hands-on coding projects, the course challenged my thinking and helped me grow as a learner. One of the most valuable skills I developed was learning how to properly format academic research and reports using APA 7.0 style, which added structure and professionalism to my work (American Psychological Association, 2020).
  </p>

  <p>
    A highlight of the course was learning about cryptographic techniques such as password hashing and encryption. I used PHP to implement these techniques on the Replit platform, where I built secure forms for SHA-256 password hashing and AES-256-CBC encryption and decryption. These exercises helped bridge the gap between classroom theory and practical coding experience, reinforcing how these technologies play a role in modern web security (Stallings, 2017).
  </p>

  <p>
    Another key area of learning was risk management in cybersecurity. I completed assignments that involved identifying vulnerabilities, conducting risk assessments, and simulating security breaches using industry-standard frameworks. These tasks introduced me to how real-world organizations manage information security threats and develop strategies to mitigate potential damage. I also explored peer-reviewed articles and academic resources on emerging topics like ransomware attacks, zero trust architecture, and endpoint detection, which broadened my understanding of the cybersecurity landscape (CISA, 2021).
  </p>

  <p>
    What I appreciated most about the course was its integration of theory with practical application. Discussions on topics such as data privacy, social engineering, and ethical hacking pushed me to think critically about real-world challenges and how security professionals respond to them. This course not only enhanced my technical skills but also inspired me to pursue further learning through certifications like CEH (Certified Ethical Hacker) and CompTIA Security+.
  </p>

  <p>
    Overall, the Information Security course was intellectually stimulating and aligned well with my academic and career goals. I now feel more confident applying core security principles in web development, risk analysis, and secure coding practices. More importantly, I’ve developed a deeper appreciation for cybersecurity as an ongoing responsibility—one that combines technical knowledge with ethical decision-making and a commitment to continuous improvement.
  </p>

